def fail(msg: str) -> None:
    raise SystemExit(f"results_charts.py: {msg}")


def need(obj, *path):
    """Follow path into obj, stopping loudly at the first missing key or null value."""
    cur = obj
    for i, k in enumerate(path):
        try:
            cur = cur[k]
        except (KeyError, IndexError, TypeError):
            fail("missing " + " > ".join(map(str, path[: i + 1])))
        if cur is None:
            fail("null value at " + " > ".join(map(str, path[: i + 1])))
    return cur


def num(obj, *path) -> float:
    v = need(obj, *path)
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        fail("not a number at " + " > ".join(map(str, path)))
    return float(v)


def load(p: Path) -> dict:
    if not p.exists():
        fail(f"missing input {p.relative_to(REPO)}")
    return json.loads(p.read_text(encoding="utf-8"))


