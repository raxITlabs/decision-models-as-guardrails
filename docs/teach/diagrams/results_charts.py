def build_blocks(charts: dict[str, Chart]) -> dict[str, str]:
    style = PAGE_CSS + "\n" + "\n".join(c.style() for c in charts.values())
    cats = "\n".join(charts[k].html(k) for k in SUITES)
    results = (f"<style>\n{style}\n</style>\n"
               f'<div class="rc-stack">\n{charts["gaps"].html("gaps")}\n{charts["overall"].html("overall")}\n</div>\n'
               '<details class="more">\n'
               '<summary>More detail: each category, score against cost <small>6 charts</small></summary>\n'
               f'<div class="body rc-stack">\n{cats}\n</div>\n</details>')
    bias = f'<div class="rc-stack">\n{charts["fairness"].html("fairness")}\n{charts["stereotypes"].html("stereotypes")}\n</div>'
    return {"results": results, "bias": bias}


def embed(blocks: dict[str, str]) -> bool:
    page = PRIMER.read_text(encoding="utf-8")
    for slot, inner in blocks.items():
        pat = re.compile(rf"<!-- results-charts:start {slot}\b.*?-->.*?<!-- results-charts:end {slot} -->", re.S)
        found = pat.findall(page)
        if len(found) != 1:
            fail(f"expected one '{slot}' marker pair in {PRIMER.name}, found {len(found)}")
        block = f"<!-- results-charts:start {slot} ({GENERATED_BY}) -->\n{inner}\n<!-- results-charts:end {slot} -->"
        page = pat.sub(lambda m: block, page)
    if chr(0x2014) in "".join(blocks.values()):
        fail("generated block contains an em dash")
    old = PRIMER.read_text(encoding="utf-8")
    if page == old:
        return False
    PRIMER.write_text(page, encoding="utf-8")
    return True


