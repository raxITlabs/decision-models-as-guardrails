# Drawing helpers (ported from gen_boards.py)


def tw(text: str, size: float, bold: bool = False) -> float:
    return len(text) * size * (0.6 if bold else 0.56)


def dot(cx: float, cy: float, r: float, kind: str) -> str:
    return f'<circle class="d-{kind}" cx="{cx:.1f}" cy="{cy:.1f}" r="{r}"></circle>'


def overlap(a, b, pad=2) -> bool:
    return not (a[2] + pad <= b[0] or b[2] + pad <= a[0] or a[3] + pad <= b[1] or b[3] + pad <= a[1])


def place(labels, dots, obstacles, bounds):
    """Greedy label placement. labels: list of dict(x, y, r, lines=[(text, size, bold)])."""
    placed = []
    for lab in labels:
        lines = lab["lines"]
        bw = max(tw(t, s, b) for t, s, b in lines)
        bh = sum(s for _, s, _ in lines) + 3 * (len(lines) - 1)
        x, y, r = lab["x"], lab["y"], lab["r"]
        g = r + 6
        cands = [
            ("start", x + g, y - bh / 2), ("end", x - g, y - bh / 2),
            ("middle", x, y - g - bh), ("middle", x, y + g),
            ("end", x - g + 2, y - g - bh + 4), ("start", x + g - 2, y - g - bh + 4),
            ("end", x - g + 2, y + g - 4), ("start", x + g - 2, y + g - 4),
            ("end", x - g, y - bh - 4), ("end", x - g, y + 4),
        ]
        cands += [(a, ax, top + k) for k in (6, 12, -6, -12) for a, ax, top in cands[:2]]
        for anchor, ax, top in cands:
            x0 = ax if anchor == "start" else ax - bw if anchor == "end" else ax - bw / 2
            box = (x0, top, x0 + bw, top + bh)
            if box[0] < bounds[0] or box[2] > bounds[2] or box[1] < bounds[1] or box[3] > bounds[3]:
                continue
            if any(overlap(box, d) for d in dots) or any(overlap(box, o) for o in obstacles):
                continue
            break
        else:
            fail(f"no label spot for {lines[0][0]} at {x:.0f},{y:.0f}")
        obstacles.append(box)
        out, base = [], top
        for t, s, b in lines:
            base += s * 0.8 if not out else s + 3
            out.append((t, s, b, anchor, ax, base))
            if len(out) == 1:
                base += s * 0.2
        placed.append((lab, out))
    return placed


def cost_label(c: float) -> str:
    return "free" if c == 0 else f"${c:.3f}"


class Chart:
    """One figure: an HTML question heading and pill(s) around a scoped SVG."""

    def __init__(self, slug: str, h: float, aria: str, body: list[str], css: dict[str, str], extra_pill: str = "",
                 start_right: bool = False, narrow: "Chart | None" = None, width: int = W):
        self.slug, self.h, self.aria, self.body, self.css, self.extra_pill = slug, h, aria, body, css, extra_pill
        self.start_right, self.narrow, self.width = start_right, narrow, width

    def style(self) -> str:
        out = [f"#rc-{self.slug} .rc-w svg {sel} {{ {rule} }}" for sel, rule in self.css.items()]
        if self.narrow:
            out += [f"#rc-{self.slug} .rc-n svg {sel} {{ {rule} }}" for sel, rule in self.narrow.css.items()]
        return "\n".join(out)

    def svg(self, cls: str) -> str:
        return (f'<div class="rc-scroll {cls}"><svg viewBox="0 0 {self.width} {self.h:.0f}" width="100%" '
                f'style="--rc-min: {self.width}px" role="img" aria-label="{escape(self.aria)}">\n'
                + "\n".join(self.body) + "\n</svg></div>\n")

    def html(self, key: str) -> str:
        pills = f'<span class="rc-pill">{escape(PILL[key])}</span>' + self.extra_pill
        # Scatters put the cheap end on the right, so a chart narrower than its box opens scrolled to the right.
        wide = self.svg("rc-w rc-end" if self.start_right else "rc-w")
        narrow = self.narrow.svg("rc-n") if self.narrow else ""
        return (f'<figure class="rc{" rc-has-n" if narrow else ""}" id="rc-{self.slug}">\n'
                f'<div class="rc-head"><h3 class="rc-q">{QUESTION[key]}</h3><div class="rc-pills">{pills}</div></div>\n'
                + wide + narrow + '<p class="rc-hint">Scroll sideways to see the whole chart.</p>\n</figure>')


