    groups, b2, bbq, not_applicable = read_bias(load(BIAS_PARTS))
    check_design(data, verdicts, groups, b2, bbq, not_applicable)
    charts = {"overall": scatter("overall", data["overall"], True), "gaps": gaps(data, verdicts)}
    for k in SUITES:
        charts[k] = scatter(k, data[k], False)
    charts["fairness"] = fairness(groups, b2, ranking)
    charts["stereotypes"] = stereotypes(bbq)
    changed = embed(build_blocks(charts))
    print(f"{len(charts)} charts; numbers match the approved design; {PRIMER.relative_to(REPO)} "
          + ("updated" if changed else "unchanged"))


