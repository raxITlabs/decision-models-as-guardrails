def read_leaderboard(lb: dict):
    """Scores and costs per category and overall; Jev-minus-Bedrock paired verdicts per category and overall."""
    impls = {}
    for imp in need(lb, "overall", "implementations"):
        iid = need(imp, "implementation")
        if iid in NAMES:
            impls[NAMES[iid]] = imp
    for n in set(NAMES.values()):
        if n not in impls:
            fail(f"leaderboard-final.json has no overall entry for {n}")

    data = {"overall": {}}
    for n, imp in impls.items():
        data["overall"][n] = (num(imp, "overall_score"), num(imp, "usd_per_1000"))
        per = []
        for s in SUITES:
            if need(imp, "suites", s, "status") != "complete":
                fail(f"{n} {s} is not complete")
            sc, c = num(imp, "suites", s, "task_score"), num(imp, "suites", s, "usd_per_1000")
            data.setdefault(s, {})[n] = (sc, c)
            per.append(sc)
        if abs(sum(per) / len(per) - data["overall"][n][0]) > 0.001:
            fail(f"{n} overall score is not the mean of its six category scores")

    def paired(pairs, a_arm, b_arm, what):
        for p in pairs:
            if (p["a"], p["b"]) == (a_arm, b_arm):
                return num(p, "difference"), num(p, "ci", "low"), num(p, "ci", "high"), bool(need(p, "separated"))
            if (p["a"], p["b"]) == (b_arm, a_arm):
                return -num(p, "difference"), -num(p, "ci", "high"), -num(p, "ci", "low"), bool(need(p, "separated"))
        fail(f"no Jev-Bedrock paired difference for {what}")

    jev, bed = impls["Jev"], impls["Bedrock"]
    verdicts = {}
    for s in SUITES:
        pairs = need(lb, "suites", s, "paired_differences")
        if s == "word_filters":
            ja, ba = need(jev, "suites", s, "subtask_arms"), need(bed, "suites", s, "subtask_arms")
            if set(ja) != set(ba):
                fail("Jev and Bedrock word-filter components differ")
            comps = [paired(pairs, ja[k], ba[k], f"word_filters/{k}") for k in sorted(ja)]
            d = sum(c[0] for c in comps) / len(comps)
            # The category interval is derivable only when every component but one has a zero-width interval
            # (both systems scored every row of it the same way in every replicate): then it is the other
            # component's interval divided by the number of components.
            live = [c for c in comps if not (c[1] == 0 == c[2])]
            if len(live) > 1:
                fail("word-filter category interval needs the joint bootstrap; it is not in leaderboard-final.json")
            lo, hi = (live[0][1] / len(comps), live[0][2] / len(comps)) if live else (0.0, 0.0)
            verdicts[s] = (d, lo, hi, lo > 0 or hi < 0)
        else:
            a_arm, b_arm = need(jev, "suites", s, "arm_id"), need(bed, "suites", s, "arm_id")
            verdicts[s] = paired(pairs, a_arm, b_arm, s)
        gap = data[s]["Jev"][0] - data[s]["Bedrock"][0]
        if abs(verdicts[s][0] - gap) > 0.001:
            fail(f"{s}: paired difference {verdicts[s][0]:.4f} is not Jev minus Bedrock ({gap:.4f})")
    verdicts["overall"] = paired(need(lb, "overall", "paired_differences"), "jev-1.13.0", "bedrock-guardrails", "overall")

    ranking = [NAMES[need(r, "implementation")] for r in need(lb, "overall", "ranking")]
    return data, verdicts, ranking


def read_bias(bp: dict):
    """B1 messages per identity group, B2 pair outcomes, BBQ correct/n."""
    systems = need(bp, "guardrail_fairness", "systems")
    counts = None
    b2 = {}
    for sysd in systems:
        name = NAMES.get(need(sysd, "system"))
        if not name:
            fail(f"unknown system {sysd['system']} in bias-parts.json")
        ids = {need(i, "identity"): int(num(i, "mentioned", "n_benign") + num(i, "mentioned", "n_harmful"))
               for i in need(sysd, "B1", "identities")}
        if counts is not None and ids != counts:
            fail("B1 identity counts differ between systems; the chart assumes one shared comment set")
        counts = ids
        c = need(sysd, "B2", "counts")
        right, wrong, flips = int(num(c, "all_correct")), int(num(c, "all_wrong")), int(num(c, "flips"))
        if right + wrong + flips != int(num(c, "evaluable")) or int(num(c, "incomplete")):
            fail(f"{name} B2 counts do not add up to its evaluable pairs")
        b2[name] = "R" * right + "W" * wrong + "C" * flips
    if counts is None:
        fail("bias-parts.json has no guardrail fairness systems")
    shown = sorted(((k, v) for k, v in counts.items() if v), key=lambda kv: (-kv[1], kv[0]))
    zero = sum(1 for v in counts.values() if not v)
    groups = [(GROUP_LABELS.get(k, k.replace("_", " ")), v) for k, v in shown] + ([(f"{zero} others", 0)] if zero else [])

    bbq, not_applicable = {}, []
    for sysd in need(bp, "decision_model_bias", "systems"):
        name = NAMES.get(need(sysd, "system"))
        if need(sysd, "status") == "not_applicable":
            not_applicable.append(name)
            continue
        cats = need(sysd, "bbq", "result", "categories")
        tot = {"ambig": [0, 0], "disambig": [0, 0]}
        for cat in cats.values():
            for k in tot:
                if k in cat:
                    tot[k][0] += int(num(cat, k, "correct"))
                    tot[k][1] += int(num(cat, k, "n"))
        if not tot["ambig"][1] or not tot["disambig"][1]:
            fail(f"{name} has no BBQ rows")
        bbq[name] = (tuple(tot["disambig"]), tuple(tot["ambig"]))
    return groups, b2, bbq, not_applicable


def check_design(data, verdicts, groups, b2, bbq, not_applicable) -> None:
    """Every number must round to what the approved design showed."""
    def places(x: float) -> int:
        s = repr(x)
        return len(s.split(".")[1]) if "." in s else 0

    def close(actual: float, shown: float) -> bool:
        return abs(actual - shown) <= 0.5 * 10 ** -places(shown) + 1e-9

    bad = []
    for key, rows in DESIGN.items():
        if set(rows) != set(data[key]):
            bad.append(f"{key}: systems {sorted(data[key])} vs design {sorted(rows)}")
            continue
        for n, (sc, c) in rows.items():
            asc, ac = data[key][n]
            if not close(asc, sc):
                bad.append(f"{key} {n} score {asc:.4f}, design {sc}")
            if not close(ac, c):
                bad.append(f"{key} {n} cost {ac:.6f}, design {c}")
    by_title = {SUITES[s]: s for s in SUITES}
    for title, j, b, g in DESIGN_GAPS:
        s = by_title[title]
        d, _, _, sep = verdicts[s]
        if not close(data[s]["Jev"][0], j) or not close(data[s]["Bedrock"][0], b):
            bad.append(f"gap chart {title}: scores differ from design")
        if (g is not None) != sep:
            bad.append(f"gap chart {title}: separated={sep}, design shows {g or 'level'}")
        elif g is not None and f"+{d:.1f}" != g:
            bad.append(f"gap chart {title}: +{d:.1f}, design {g}")
    if f"+{verdicts['overall'][0]:.1f}" != DESIGN_OVERALL_GAP or not verdicts["overall"][3]:
        bad.append(f"overall gap +{verdicts['overall'][0]:.1f}, design {DESIGN_OVERALL_GAP}")
    if groups != DESIGN_B1:
        bad.append(f"B1 groups {groups}, design {DESIGN_B1}")
    if b2 != DESIGN_B2:
        bad.append(f"B2 patterns {b2}, design {DESIGN_B2}")
    if bbq != DESIGN_BBQ:
        bad.append(f"BBQ {bbq}, design {DESIGN_BBQ}")
    if not_applicable != ["Bedrock"]:
        bad.append(f"BBQ not applicable for {not_applicable}, design: Bedrock only")
    if bad:
        fail("saved results and the approved design disagree; nothing written:\n  " + "\n  ".join(bad))


