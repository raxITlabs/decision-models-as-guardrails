def fairness(groups, b2, ranking) -> Chart:
    css = {**BASE_CSS,
           ".pt": f"font-size: 16px; font-weight: 600; fill: {INK2}",
           ".bar": f"fill: {OPEN}; stroke: {OPEN_RING}; stroke-width: 1",
           ".bv": f"font-size: 14px; font-weight: 600; fill: {INK2}; text-anchor: middle",
           ".bl": f"font-size: 14px; fill: {MUTED}; text-anchor: middle",
           ".need": f"stroke: {MUTED}; stroke-width: 1.5; stroke-dasharray: 6 4",
           ".needt": f"font-size: 14px; font-weight: 600; fill: {MUTED}; text-anchor: end",
           ".base": "stroke: #a8977f; stroke-width: 1",
           ".nm": f"font-size: 15px; font-weight: 500; fill: {MUTED}",
           ".nmh": "font-size: 16px; font-weight: 700",
           ".h-jev": f"fill: {JEV}", ".h-bed": f"fill: {BED_INK}",
           ".ok": f"fill: {GREEN}", ".chg": f"fill: {INK2}",
           ".box": f"fill: none; stroke: {MUTED}; stroke-width: 1.5", ".x": f"stroke: {MUTED}; stroke-width: 1.5",
           ".lg": f"font-size: 14px; fill: {INK2}"}
    s = ['<text class="pt" x="16" y="28">Messages per group</text>']
    need_n, scale = 30, 4
    base = 70 + need_n * scale
    if max(n for _, n in groups) > need_n + 8:
        fail("a group has more messages than the bar area was drawn for")
    s.append(f'<line class="need" x1="16" x2="{W - 16}" y1="{base - need_n * scale}" y2="{base - need_n * scale}"></line>'
             f'<text class="needt" x="{W - 16}" y="{base - need_n * scale - 8}">{need_n} needed to compare</text>')
    s.append(f'<line class="base" x1="16" x2="{W - 16}" y1="{base}" y2="{base}"></line>')
    first, last = 40, W - 28
    step = (last - first) / (len(groups) - 1)
    # "|" marks a line break; a label wider than a column breaks at its first space
    shown = [g if "|" in g or tw(g, 14) <= step else g.replace(" ", "|", 1) for g, _ in groups]
    widths = [max(tw(part, 14) for part in g.split("|")) for g in shown]
    for i in range(len(groups) - 1):
        if (widths[i] + widths[i + 1]) / 2 > step:
            fail(f"group labels {groups[i][0]} and {groups[i + 1][0]} would overlap")
    for i, (g, (_, n)) in enumerate(zip(shown, groups)):
        cx = first + i * step
        if n:
            s.append(f'<rect class="bar" x="{cx - 20:.1f}" y="{base - n * scale}" width="40" height="{n * scale}" rx="2"></rect>')
        s.append(f'<text class="bv" x="{cx:.1f}" y="{base - n * scale - 8}">{n}</text>')
        for k, part in enumerate(g.split("|")):
            s.append(f'<text class="bl" x="{cx:.1f}" y="{base + 20 + k * 17}">{escape(part)}</text>')
    top = base + 84
    s.append(f'<text class="pt" x="16" y="{top}">Identity-swapped pairs</text>')
    legend = [("ok", "same, right"), ("box", "same, wrong"), ("chg", "changed")]
    lx = W - 16 - sum(21 + tw(t, 14) for _, t in legend) - 18 * (len(legend) - 1)
    if lx < 16 + tw("Identity-swapped pairs", 16, True) + 16:
        fail("pairs legend would overlap its title")
    for kind, text in legend:
        if kind == "box":
            s.append(f'<rect class="box" x="{lx + 0.75:.1f}" y="{top - 12.25}" width="12.5" height="12.5" rx="2"></rect>'
                     f'<line class="x" x1="{lx + 3.5:.1f}" y1="{top - 9.5}" x2="{lx + 10.5:.1f}" y2="{top - 2.5}"></line>'
                     f'<line class="x" x1="{lx + 10.5:.1f}" y1="{top - 9.5}" x2="{lx + 3.5:.1f}" y2="{top - 2.5}"></line>')
        else:
            s.append(f'<rect class="{kind}" x="{lx:.1f}" y="{top - 13}" width="14" height="14" rx="2"></rect>')
        s.append(f'<text class="lg" x="{lx + 21:.1f}" y="{top}">{text}</text>')
        lx += 21 + tw(text, 14) + 18
    order = list(HEROES) + [n for n in ranking if n not in HEROES]
    if set(order) != set(b2):
        fail("B2 systems differ from the ranked systems")
    if max(tw(n, 16, True) if n in HEROES else tw(n, 15) for n in order) + 16 + 12 > 132:
        fail("a system name would run into the pair squares")
    for i, name in enumerate(order):
        y = top + 24 + i * 38
        cls = "nmh h-jev" if name == "Jev" else "nmh h-bed" if name == "Bedrock" else "nm"
        s.append(f'<text class="{cls}" x="16" y="{y + 18}">{name}</text>')
        for k, c in enumerate(b2[name]):
            x = 132 + k * 34
            if c == "R":
                s.append(f'<rect class="ok" x="{x}" y="{y}" width="26" height="26" rx="3"></rect>')
            elif c == "C":
                s.append(f'<rect class="chg" x="{x}" y="{y}" width="26" height="26" rx="3"></rect>')
            else:
                s.append(f'<rect class="box" x="{x + 0.75}" y="{y + 0.75}" width="24.5" height="24.5" rx="3"></rect>'
                         f'<line class="x" x1="{x + 7}" y1="{y + 7}" x2="{x + 19}" y2="{y + 19}"></line>'
                         f'<line class="x" x1="{x + 19}" y1="{y + 7}" x2="{x + 7}" y2="{y + 19}"></line>')

    def said(name):
        p = b2[name]
        bits = [f"same and right in {p.count('R')}"]
        if p.count("W"):
            bits.append(f"same and wrong in {p.count('W')}")
        if p.count("C"):
            bits.append(f"changed its decision in {p.count('C')}")
        return f"{name} " + ", ".join(bits) + "."

    aria = ("Bias: fairness across groups. Messages per identity group against the 30 needed to compare: "
            + ", ".join(f"{g.replace('|', ' ')} {n}" for g, n in groups)
            + f". Identity-swapped pairs, {len(b2['Jev'])} per system. " + " ".join(said(n) for n in order))
    return Chart("fairness", top + 24 + len(order) * 38 + 8, aria, s, css)


