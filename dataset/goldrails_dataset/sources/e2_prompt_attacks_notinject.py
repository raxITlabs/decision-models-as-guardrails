"""NotInject (Li et al., InjecGuard, 2024): 339 benign prompts that each contain one to three words common in prompt
injections ("ignore", "bypass", "override", "unfiltered", ...). MIT. Built to measure over-defence: a detector that
keys on trigger words flags them.

The source's splits are ``NotInject_one``, ``_two`` and ``_three`` (number of trigger words); there is no train/test
split and the rows were not used for training by the authors, so all three are used and none is flagged as train.
Multilingual rows are excluded (edition 2 is English). Rows are generated by an LLM and checked by the authors, so
label_basis is ``synthetic_reviewed``.

Subtask assignment (first labeller, Claude, 2 October 2026). Every row is benign. A row whose trigger words are
jailbreak words goes to ``jailbreak``, one whose words are about secrets, prompts or disclosure goes to ``leakage``,
everything else to ``injection``.
"""
from __future__ import annotations

import ast

from .e2_prompt_attacks_common import is_english, record, short_hash

NAME, LICENCE = "notinject", "mit"
REVISION = "847ae76cf8fea5ed325429e569ae8cfef022d2e0"
URL = "https://huggingface.co/datasets/leolee99/NotInject"
SPLITS = ("NotInject_one", "NotInject_two", "NotInject_three")
JAILBREAK_WORDS = {"jailbreak", "unfiltered", "uncensored", "unrestricted", "dan", "roleplay", "role-play", "pretend",
                   "immoral", "unethical", "illegal", "amoral", "bypass", "evade", "circumvent", "loophole", "exploit"}
LEAK_WORDS = {"prompt", "reveal", "secret", "password", "confidential", "disclose", "expose", "leak", "system",
              "hidden", "classified", "private", "instructions", "initial"}


def subtask_for(words: list) -> str:
    ws = {w.lower().strip() for w in words}
    if ws & JAILBREAK_WORDS:
        return "jailbreak"
    if ws & LEAK_WORDS:
        return "leakage"
    return "injection"


def load(limit=None) -> list:
    from datasets import load_dataset
    out = []
    for split in SPLITS:
        ds = load_dataset("leolee99/NotInject", split=split, revision=REVISION)
        for i, row in enumerate(ds):
            text = row["prompt"] or ""
            try:
                words = list(ast.literal_eval(row["word_list"]))
            except (ValueError, SyntaxError):
                words = []
            exclude = None
            if row.get("category") == "Multilingual" or not is_english(text):
                exclude = "non_english"
            out.append(record(
                source=NAME, source_id=f"{split}:{i}", licence=LICENCE, subtask=subtask_for(words), text=text,
                expected="no", label_basis="synthetic_reviewed", revision=REVISION, upstream_split=split,
                train_split=False,
                rationale=f"ordinary request that happens to use trigger word(s) {words}; it gives no instruction "
                          "to override, escape or reveal the assistant's configuration; first labeller agrees",
                source_label=f"benign;category={row.get('category')}", group=f"notinject-{short_hash(text)}",
                exclude_reason=exclude, extra={"trigger_words": words, "source_category": row.get("category")},
            ))
    return out[:limit] if limit else out
