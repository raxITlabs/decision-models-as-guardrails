"""HarmBench classifier validation set, text behaviours (edition 2 content, subtask output). MIT.

602 model completions to HarmBench test cases, each labelled by three humans for whether the completion is an
instance of the harmful behaviour. A reply is judged next to the request that produced it, so the test case is the
context turn. Only unanimous rows are eligible (3/3 yes or 0/3 yes); split votes keep exclude_reason
"human_split_vote" and the vote share in expected_distribution.

This is HarmBench's held-out validation set for classifiers, not a training split; HarmBench publishes no other
human-labelled completions. The completions were generated by several open and closed models (recorded per row in
the notes); the dataset is not owned by any of those vendors. Grouped by BehaviorID, shared with
e2_content_harmbench.
"""
from __future__ import annotations

import json
import urllib.request

from ..records import Category, Provenance, Record, State, make_id
from .base import now

NAME, LICENCE = "e2_content_harmbench_cls", "mit"
COMMIT = "8e1604d1171fe8a48d8febecd22f600e462bdcdd"   # pinned centerforaisafety/HarmBench commit
URL = f"https://raw.githubusercontent.com/centerforaisafety/HarmBench/{COMMIT}/data/classifier_val_sets/text_behaviors_val_set.json"
UPSTREAM_SPLIT = "classifier_val"
HUMANS = ("human_0", "human_1", "human_2")


def fetch() -> dict:
    return json.loads(urllib.request.urlopen(URL).read().decode("utf-8"))


def load(limit=None, data=None) -> list:
    data = data if data is not None else fetch()
    out = []
    for behavior_id in sorted(data):
        for i, row in enumerate(data[behavior_id]):
            votes = [int(row[h]) for h in HUMANS if row.get(h) is not None]
            if len(votes) != len(HUMANS) or not (row.get("generation") or "").strip():
                continue
            share = sum(votes) / len(votes)
            unanimous = share in (0.0, 1.0)
            expected = "yes" if share >= 0.5 else "no"
            sid = f"{behavior_id}:{i}"
            out.append(Record(
                id=make_id("F1", NAME, sid), feature="F1", subtask="output",
                state=State(role="assistant", text=row["generation"].strip(),
                            context=[{"role": "user", "text": row["test_case"]}]),
                category=Category(ailuminate=None if expected == "yes" else "benign", bedrock=None if expected == "yes" else "NONE",
                                  source_label=f"human_votes={sum(votes)}/3"),
                labels=["no", "yes"], expected=expected, group=f"harmbench:{behavior_id}",
                expected_distribution={"yes": share, "no": 1 - share},
                provenance=Provenance(source=NAME, source_id=sid, licence=LICENCE, label_basis="human", imported_at=now(),
                                      contamination=["harmbench-public-2024"],
                                      exclude_reason=None if unanimous else "human_split_vote",
                                      notes=json.dumps({"generator": row.get("model"), "method": row.get("method"),
                                                        "upstream_split": UPSTREAM_SPLIT, "commit": COMMIT}, sort_keys=True)),
            ))
            if limit and len(out) >= limit:
                return out
    return out
