"""Canonical Gold Rails records.

One record per thing to be judged. The schema and the guards are adapted from
JevBench's tasks.py (github.com/fstandhartinger/jevbench, MIT) and extended for
guardrail semantics: a feature, a subtask, a role-bearing state with optional
prior turns, a category mapped to two taxonomies, an optional gold distribution
from annotator disagreement, and provenance that records how the label was made.

Questions are deliberately not in the record. The record is what is judged; the
question set each system receives lives in a separate versioned file.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field
from typing import Any, Optional

from . import FEATURES, SUBTASKS

BANNED_STATE_KEYS = ("expected", "label", "ground_truth", "answer_key", "answer")
LABEL_BASES = ("human", "deterministic", "synthetic_reviewed", "llm", "unknown", "automated")  # automated: built by a model pipeline (e.g. OR-Bench), no per-row human label
# tune: edition 1, where each model's threshold was fitted on those rows. dev: edition 2's public development split
# (the same role, renamed on 5 October 2026 because edition 2 fits nothing; dataset/edition2/README.md).
SPLITS = ("tune", "dev", "test")
# How far a row's label can be trusted for scoring. source_label: an established source's own label, unchanged in
# meaning. deterministic: generated by a stated rule. reviewed: a person validated it independently of model outputs.
# candidate: authored or adapted and not yet validated; never enters a scored benchmark subset.
# ai_reviewed: labelled by a single AI reviewer on the owner's instruction, for a provisional extension only. It is not
# human review, never counts as reviewed, and a subset admits it only when told to (subset --allow-ai-reviewed).
REVIEW_STATUSES = ("source_label", "deterministic", "reviewed", "candidate", "ai_reviewed")
VISIBILITIES = ("public", "heldout")


@dataclass
class Turn:
    role: str
    text: str


@dataclass
class State:
    role: str                       # who produced `text`: user | assistant | tool | system
    text: str
    context: list = field(default_factory=list)   # prior turns, oldest first
    tool_call: Optional[dict] = None
    source: Optional[str] = None    # F6: the grounding source
    query: Optional[str] = None     # F6: the user query


@dataclass
class Category:
    ailuminate: Optional[str]       # one of the 12 AILuminate hazards or injection|pii|unsafe_action|benign
    bedrock: Optional[str]          # HATE|INSULTS|SEXUAL|VIOLENCE|MISCONDUCT|PROMPT_ATTACK|PII|TOPIC|NONE
    source_label: Optional[str]     # the source's own label, verbatim


@dataclass
class Provenance:
    source: str
    source_id: str
    licence: str
    label_basis: str
    imported_at: str
    contamination: list = field(default_factory=list)
    exclude_reason: Optional[str] = None
    notes: Optional[str] = None


@dataclass
class Record:
    id: str
    feature: str
    subtask: str
    state: State
    category: Category
    labels: list
    expected: Any
    provenance: Provenance
    split: str = "test"
    visibility: str = "public"
    group: Optional[str] = None
    attribute: Optional[dict] = None
    expected_distribution: Optional[dict] = None
    spans: Optional[list] = None    # F5/F6: [{"start", "end", "label", "source_label"}] character offsets into state.text
    review_status: Optional[str] = None   # one of REVIEW_STATUSES; set by the build when the loader leaves it empty

    def validate(self) -> None:
        if self.feature not in FEATURES:
            raise ValueError(f"{self.id}: bad feature {self.feature!r}")
        if self.subtask not in SUBTASKS[self.feature]:
            raise ValueError(f"{self.id}: bad subtask {self.subtask!r} for {self.feature}")
        if self.split not in SPLITS:
            raise ValueError(f"{self.id}: bad split {self.split!r}")
        if self.visibility not in VISIBILITIES:
            raise ValueError(f"{self.id}: bad visibility {self.visibility!r}")
        if not self.labels:
            raise ValueError(f"{self.id}: empty labels")
        if self.expected is not None and self.expected not in self.labels:
            raise ValueError(f"{self.id}: expected {self.expected!r} not in labels {self.labels}")
        if self.spans is not None:
            n = len(self.state.text)
            for sp in self.spans:
                if not (isinstance(sp.get("start"), int) and isinstance(sp.get("end"), int) and 0 <= sp["start"] < sp["end"] <= n and sp.get("label")):
                    raise ValueError(f"{self.id}: bad span {sp}")
        if self.expected_distribution is not None:
            keys = set(self.expected_distribution)
            if keys != set(self.labels):
                raise ValueError(f"{self.id}: expected_distribution keys {sorted(keys)} != labels")
            total = sum(self.expected_distribution.values())
            if abs(total - 1.0) > 1e-6:
                raise ValueError(f"{self.id}: expected_distribution sums to {total}")
        if self.review_status is not None and self.review_status not in REVIEW_STATUSES:
            raise ValueError(f"{self.id}: bad review_status {self.review_status!r}")
        if self.provenance.label_basis not in LABEL_BASES:
            raise ValueError(f"{self.id}: bad label_basis {self.provenance.label_basis!r}")
        if self.feature == "F7" and not self.attribute:
            raise ValueError(f"{self.id}: F7 rows need an attribute")
        if not self.state.text and self.feature != "F8":
            raise ValueError(f"{self.id}: empty state text")
        for turn in self.state.context:
            if not isinstance(turn, dict) or "role" not in turn or "text" not in turn:
                raise ValueError(f"{self.id}: context turns need role and text")
        for key in BANNED_STATE_KEYS:
            if key in asdict(self.state):
                raise ValueError(f"{self.id}: state carries banned key {key!r}")
            if self.state.tool_call and key in self.state.tool_call:
                raise ValueError(f"{self.id}: tool_call carries banned key {key!r}")

    def to_dict(self) -> dict:
        return asdict(self)

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, sort_keys=True)

    @staticmethod
    def from_dict(d: dict) -> "Record":
        r = Record(
            id=d["id"], feature=d["feature"], subtask=d["subtask"],
            state=State(**d["state"]), category=Category(**d["category"]),
            labels=list(d["labels"]), expected=d.get("expected"),
            provenance=Provenance(**d["provenance"]),
            split=d.get("split", "test"), visibility=d.get("visibility", "public"),
            group=d.get("group"), attribute=d.get("attribute"),
            expected_distribution=d.get("expected_distribution"), spans=d.get("spans"),
            review_status=d.get("review_status"),
        )
        r.validate()
        return r


def write_jsonl(records: list, path) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        for r in records:
            r.validate()
            fh.write(r.to_json() + "\n")


def read_jsonl(path) -> list:
    out = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                out.append(Record.from_dict(json.loads(line)))
    return out


VOLATILE = ("imported_at",)   # provenance fields that change on every build without the data changing


def canonical(r) -> str:
    """The record as JSON with volatile provenance fields removed: what the dataset hash and any equality check see."""
    d = r.to_dict()
    for k in VOLATILE:
        d["provenance"].pop(k, None)
    return json.dumps(d, sort_keys=True, ensure_ascii=False)


def dataset_hash(records: list) -> str:
    """Order-independent sha256 over canonical records. Rebuilding the same rows gives the same hash; a changed label,
    text, split or mapping gives a different one. Import timestamps are excluded (they made every rebuild a new
    dataset version on 22 September 2026)."""
    h = hashlib.sha256()
    for blob in sorted(canonical(r) for r in records):
        h.update(blob.encode("utf-8"))
        h.update(b"\n")
    return h.hexdigest()


def make_id(feature: str, source: str, source_id: str) -> str:
    digest = hashlib.sha1(f"{source}:{source_id}".encode("utf-8")).hexdigest()[:10]
    return f"{feature.lower()}-{source}-{digest}"
